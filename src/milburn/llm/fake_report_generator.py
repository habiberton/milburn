"""Deterministic, offline report generator.

Produces a schema-valid AnalysisReport without any I/O or model call, citing
whatever tools appear in input.tool_outputs. This is what makes the whole
graph testable offline: if the graph runs with the fake, the graph doesn't know
what an LLM is. Same input -> same output, always.
"""

from typing import Any

from milburn.llm.base import ReportInput
from milburn.model import AnalysisReport, EvidenceRef, SignalClaim

# Map known tool names onto report signal categories. Unknown tools fall back to
# "trend" so the fake stays schema-valid no matter what tools were run.
_TOOL_CATEGORIES: dict[str, str] = {
    "sma": "trend",
    "ema": "trend",
    "swing": "trend",
    "swing_points": "trend",
    "rsi": "momentum",
    "macd": "momentum",
    "atr": "volatility",
    "bollinger": "volatility",
    "bollinger_bands": "volatility",
    "volume": "volume",
    "volume_stats": "volume",
    "support_resistance": "levels",
    "levels": "levels",
}


def _category_for(tool_name: str) -> str:
    return _TOOL_CATEGORIES.get(tool_name, "trend")


def _representative_value(result: Any) -> tuple[str, str | float | bool]:
    """Pull one (field, value) pair out of a serialized tool result for evidence.

    Tool results are serialized ToolResult dicts ({"latest": {...}, ...}).
    Falls back gracefully for any other shape so the fake never raises.
    """
    if isinstance(result, dict):
        latest = result.get("latest")
        if isinstance(latest, dict) and latest:
            field = sorted(latest)[0]
            value = latest[field]
            return field, value if isinstance(value, str | float | bool) else str(value)
        if isinstance(latest, str | float | bool):
            return "latest", latest
        if result:
            field = sorted(result)[0]
            value = result[field]
            return field, value if isinstance(value, str | float | bool) else str(value)
    return "value", str(result)


class FakeReportGenerator:
    """Deterministic ReportGenerator for tests and --llm fake runs."""

    def generate_report(self, input: ReportInput) -> AnalysisReport:
        signals: list[SignalClaim] = []

        # Sorted for determinism: same tool_outputs -> identical report.
        for tool_name in sorted(input.tool_outputs):
            field, value = _representative_value(input.tool_outputs[tool_name])
            signals.append(
                SignalClaim(
                    category=_category_for(tool_name),  # type: ignore[arg-type]
                    claim=f"[fake] {tool_name} reported {field}={value}.",
                    evidence=[EvidenceRef(tool=tool_name, field=field, value=value)],
                    confidence="low",
                )
            )

        if not signals:
            signals.append(
                SignalClaim(
                    category="trend",
                    claim="[fake] No tools were executed; this is a placeholder signal.",
                    evidence=[],
                    confidence="low",
                )
            )

        return AnalysisReport(
            summary=(
                f"[fake-report-generator] Deterministic report for prompt "
                f"{input.prompt!r} over {len(input.tool_outputs)} tool result(s)."
            ),
            data=dict(input.candle_summary),
            signals=signals,
            conflicts=[],
            warnings=["Generated by FakeReportGenerator - not a real analysis."],
            next_steps=["Run with --llm smoke/default for a model-generated report."],
        )
